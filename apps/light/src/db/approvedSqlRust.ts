/**
 * Render the approved SQL list as the Rust source Rust checks against (L-243).
 *
 * Pure: a list in, a file's text out. `approved-sql.contract.test.ts` compares
 * the committed file with what this renders, and fails when they differ — so
 * the two halves of the allow-list cannot drift. `pnpm approved-sql` rewrites
 * the file after a statement is added or changed.
 *
 * Raw string literals (`r##"…"##`) keep each statement byte for byte: Rust
 * compares the text the page sends against these exactly.
 */

export const APPROVED_SQL_RS = 'apps/light/src-tauri/src/approved_sql.rs';

export function renderApprovedSqlRust(statements: readonly string[]): string {
  const sorted = [...statements].sort();
  for (const sql of sorted) {
    if (sql.includes('"##')) throw new Error(`cannot embed in a raw string: ${sql}`);
    if (sql.trim() === '') throw new Error('an empty statement cannot be approved');
  }
  const lines = sorted.map((sql) => `    r##"${sql}"##,`);
  return [
    '// GENERATED by `pnpm approved-sql` — do not edit.',
    '//',
    '// Every SQL statement the app may run (L-243). `sql_gate.rs` refuses any',
    '// other text, byte for byte. The list is written from `approved()` calls in',
    '// `apps/light/src/db/`, and `approved-sql.contract.test.ts` fails when this',
    '// file is not exactly what they render.',
    '',
    `pub const APPROVED_SQL: &[&str] = &[`,
    ...lines,
    '];',
    '',
  ].join('\n');
}
